import { promises as fs } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

/** Vendor the onnxruntime native binding + runtime libraries for a target
 *  platform/arch into vendor/onnxruntime-node/, so the tsconfig paths mapping
 *  serves it to both `bun run` (source) and `bun build --compile` (embedded
 *  .node), with the dylib found via @executable_path on macOS.
 *
 *  Defaults to the host platform/arch; `--platform`/`--arch` let a release
 *  build vendor a cross target. When the target has no published binding
 *  (onnxruntime dropped macOS x64 in 1.24), a no-op shim is written so the
 *  binary still builds and the semantic lane degrades instead of failing. */

const root = path.join(import.meta.dir, "..", "..");
const argv = process.argv.slice(2);
function opt(name: string): string | undefined {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : undefined;
}
const platform = opt("platform") ?? process.platform;
const arch = opt("arch") ?? process.arch;

const src = path.join(root, "node_modules", "onnxruntime-node", "bin", "napi-v6", platform, arch);
const dst = path.join(root, "vendor", "onnxruntime-node");
const MARKER = "// vendored-onnx-entry (generated by scripts/build/vendor-onnx.ts)\n";

const realShim =
  MARKER +
  `try {\n  module.exports = require("./onnxruntime_binding.node");\n} catch (e) {\n  module.exports = { __dlopenError: String(e) };\n}\n`;
const stubShim =
  MARKER +
  `// No onnxruntime binding is published for ${platform}/${arch}; the semantic\n// lane is unavailable and degrades to lexical/graph results.\nmodule.exports = { __onnxUnavailable: "${platform}/${arch}" };\n`;

const exists = (p: string) => fs.stat(p).then(() => true).catch(() => false);
const isNative = (f: string) => f.endsWith(".dylib") || f.includes(".so") || f.endsWith(".dll");

await fs.mkdir(dst, { recursive: true });
await fs.writeFile(
  path.join(dst, "package.json"),
  JSON.stringify({ name: "onnxruntime-node-vendored", version: "1.0.0", main: "index.js" }, null, 2) + "\n",
);

// clear any previously vendored target so a platform switch cannot leave a
// stale binding or the wrong runtime library behind
for (const f of await fs.readdir(dst)) {
  if (f === "onnxruntime_binding.node" || isNative(f)) await fs.rm(path.join(dst, f), { force: true });
}

const binding = path.join(src, "onnxruntime_binding.node");
if (!(await exists(binding))) {
  await fs.writeFile(path.join(dst, "index.js"), stubShim);
  console.warn(`vendored onnxruntime: no binding for ${platform}/${arch}; semantic disabled`);
  process.exit(0);
}

const libs =
  platform === "darwin"
    ? ["libonnxruntime.1.24.3.dylib"]
    : platform === "linux"
      ? ["libonnxruntime.so.1"]
      : (await fs.readdir(src)).filter((f) => f.endsWith(".dll"));

await fs.copyFile(binding, path.join(dst, "onnxruntime_binding.node"));
const copied = ["onnxruntime_binding.node"];
for (const f of libs) {
  await fs.copyFile(path.join(src, f), path.join(dst, f));
  copied.push(f);
}
await fs.writeFile(path.join(dst, "index.js"), realShim);
console.log(`vendored onnxruntime (${platform}/${arch}): ${copied.join(", ")}`);

// macOS: the addon is embedded and dlopen'd from a temp dir, so @loader_path
// cannot find the sibling dylib; add @executable_path so the main binary's
// directory is searched. Only macOS has install_name_tool.
if (platform === "darwin") {
  if (process.platform !== "darwin") {
    console.warn("vendored onnxruntime: cannot set @executable_path rpath off macOS");
  } else {
    const node = path.join(dst, "onnxruntime_binding.node");
    const check = spawnSync("otool", ["-l", node], { encoding: "utf8" });
    if (!check.stdout.includes("@executable_path")) {
      const r = spawnSync("install_name_tool", ["-add_rpath", "@executable_path", node]);
      if (r.status !== 0) console.error("install_name_tool failed (non-fatal):", r.stderr?.toString());
    }
  }
}
